def create_task(title: str, description: str, due_date: str | None = None) -> dict:
    title = (title or "").strip()
    description = (description or "").strip()
    if not title or not description:
        raise ValueError("A task title and description are required.")

    try:
        parsed_due_date = parse_due_date(due_date) if due_date else None
    except ValueError as exc:
        raise ValueError("The due date must use YYYY-MM-DD format.") from exc

    with SessionLocal() as db:
        task = Task(title=title, description=description, due_date=parsed_due_date, status="pending")
        db.add(task)
        db.commit()
        db.refresh(task)
        return {
            "id": task.id,
            "title": task.title,
            "description": task.description,
            "due_date": task.due_date.isoformat() if task.due_date else None,
            "status": task.status,
        }


def get_tasks(status: str | None = None) -> list[dict]:
    with SessionLocal() as db:
        query = db.query(Task)
        if status and status.lower() != "all":
            query = query.filter(Task.status == status.lower())
        tasks = query.order_by(Task.created_at.desc()).all()
        return [
            {
                "id": task.id,
                "title": task.title,
                "description": task.description,
                "due_date": task.due_date.isoformat() if task.due_date else None,
                "status": task.status,
            }
            for task in tasks
        ]


def complete_task(task_id: int) -> dict:
    try:
        task_id_value = int(task_id)
    except (TypeError, ValueError) as exc:
        raise ValueError("task_id must be a valid integer.") from exc

    with SessionLocal() as db:
        task = db.query(Task).filter(Task.id == task_id_value).first()
        if not task:
            raise ValueError(f"Task #{task_id_value} was not found.")
        task.status = "completed"
        db.commit()
        db.refresh(task)
        return {
            "id": task.id,
            "title": task.title,
            "status": task.status,
        }


async def generate_study_plan(subject: str, days: int, daily_minutes: int) -> dict:
    subject = (subject or "").strip()
    if not subject:
        raise ValueError("A subject is required.")

    try:
        days_value = int(days)
        daily_minutes_value = int(daily_minutes)
    except (TypeError, ValueError) as exc:
        raise ValueError("days and daily_minutes must be integers.") from exc

    if days_value < 1 or days_value > 30:
        raise ValueError("days must be between 1 and 30.")
    if daily_minutes_value < 15 or daily_minutes_value > 600:
        raise ValueError("daily_minutes must be between 15 and 600.")

    plan = await llm_service.generate_study_plan(
        subject=subject,
        days=days_value,
        level="Beginner",
        daily_minutes=daily_minutes_value,
        notes="Generated by the agent.",
    )
    with SessionLocal() as db:
        payload = plan.model_dump()
        saved = save_plan_to_db(db, payload)
    return saved


