async def run_agent(message: str) -> dict:
    if not message or not message.strip():
        raise ValueError("The agent message cannot be empty.")

    messages = [
        {
            "role": "system",
            "content": (
                "You are a helpful study assistant. Use the available tools when the user asks to create, list, or complete tasks, "
                "or generate a study plan. If a tool call is needed, choose the correct one and use the provided arguments."
            ),
        },
        {"role": "user", "content": message},
    ]

    for step in range(5):
        response = llm_service.chat_completion(messages=messages, tools=AGENT_TOOLS, tool_choice="auto")
        message_obj = response.choices[0].message

        if not getattr(message_obj, "tool_calls", None):
            final_answer = message_obj.content or "I can help with study planning and tasks."
            if any(keyword in message.lower() for keyword in ["create task", "show my tasks", "complete", "pending", "plan", "study plan"]):
                raise LLMConfigurationError(
                    "The configured model does not support tool calling, so the agent cannot execute task actions safely."
                )
            return {"answer": final_answer, "tool_used": False}

        assistant_tool_call = {
            "role": "assistant",
            "tool_calls": [
                {
                    "id": call.id,
                    "type": call.type,
                    "function": {
                        "name": call.function.name,
                        "arguments": call.function.arguments,
                    },
                }
                for call in message_obj.tool_calls
            ],
        }
        messages.append(assistant_tool_call)

        tool_results = []
        for call in message_obj.tool_calls:
            try:
                arguments = json.loads(call.function.arguments)
                name = call.function.name
                if name == "create_task":
                    result = create_task(**arguments)
                elif name == "get_tasks":
                    result = get_tasks(**arguments)
                elif name == "complete_task":
                    result = complete_task(**arguments)
                elif name == "generate_study_plan":
                    result = await generate_study_plan(**arguments)
                else:
                    result = {"error": f"Unsupported tool: {name}"}
            except Exception as exc:  # pragma: no cover - safety guard for tool execution issues
                result = {"error": str(exc)}

            tool_results.append(
                {
                    "role": "tool",
                    "tool_call_id": call.id,
                    "name": name,
                    "content": json.dumps(result),
                }
            )

        messages.extend(tool_results)

    return {"answer": "The agent reached the maximum number of steps while trying to complete the request.", "tool_used": True}
